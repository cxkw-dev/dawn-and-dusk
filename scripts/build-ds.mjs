// Builds the distributable design system from ds/ (npm run build:ds; also the first step of dev and build):
//   ds/dawn-and-dusk.css|js   — source entry points (@import / import lists), regenerated from the folder contents
//   release/dawn-and-dusk.css — one self-contained stylesheet (fonts, tokens, base, every component)
//   release/dawn-and-dusk.js  — every behavior in one plain script (no modules, no dependencies)
//   release/tokens.css        — tokens only
//   release/icons.svg         — the Solar icon sprite (<use href="#dd-i-NAME"/>)
// copies the release files into the agent skill (skill/dawn-and-dusk/assets) and the docs (site/public/release),
// generates the skill's references/tokens.md and references/components.md, and fills the versioned release URLs (install
// command, starter downloads) in the READMEs and the skill. (references/components/*.md come from the built docs:
// scripts/build-skill-examples.mjs.)
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tailwindTheme } from './tailwind-entry.mjs';
import { listDs, readDs as read, releaseAsset, stylesheetParts, tokenBlock } from './ds-source.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const ds = join(root, 'ds');
const release = join(root, 'release');
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));

const { components, fonts, tokens, core } = await stylesheetParts();
// theme.js first so the stored theme applies before anything else runs.
const behaviors = (await listDs('behaviors', '.js')).sort((a, b) => (a === 'theme.js' ? -1 : b === 'theme.js' ? 1 : a.localeCompare(b)));

const header = (what) => `/* dawn & dusk v${pkg.version} — ${what}. Generated by scripts/build-ds.mjs; edit the files in ds/ instead. */\n`;

// Source entry points.
await writeFile(join(ds, 'dawn-and-dusk.css'), header('stylesheet entry') + [
  "@import './fonts.css';", "@import './tokens.css';", "@import './base.css';",
  ...components.map((f) => `@import './components/${f}';`),
].join('\n') + '\n');
await writeFile(join(ds, 'dawn-and-dusk.js'), header('behaviors entry') + behaviors.map((f) => `import './behaviors/${f}';`).join('\n') + '\n');

// Release bundles.
await mkdir(release, { recursive: true });
await writeFile(join(release, 'dawn-and-dusk.css'), [header('complete stylesheet'), fonts, tokens, core].join('\n'));
await writeFile(join(release, 'tokens.css'), header('tokens') + tokens);
const js = [header('behaviors (plain script, load with <script defer>)')];
for (const f of behaviors) js.push(`\n/* ===== behaviors/${f} ===== */\n` + (await read(`behaviors/${f}`)));
await writeFile(join(release, 'dawn-and-dusk.js'), js.join('\n'));

await copyFile(join(ds, 'icons/icons.svg'), join(release, 'icons.svg'));

// Copies for the skill and the docs site.
for (const dest of [join(root, 'skill/dawn-and-dusk/assets'), join(root, 'site/public/release')]) {
  await mkdir(dest, { recursive: true });
  for (const f of ['dawn-and-dusk.css', 'dawn-and-dusk.js', 'tokens.css', 'icons.svg']) await copyFile(join(release, f), join(dest, f));
}

// Agent skill references, generated so they never drift from the source.
const skillRef = join(root, 'skill/dawn-and-dusk/references');
await mkdir(skillRef, { recursive: true });
const rows = (body) => [...body.matchAll(/--dd-([\w-]+):\s*([^;]+);(?:[ \t]*\/\*[ \t]*(.*?)[ \t]*\*\/)?/g)].map((m) => ({ name: m[1], value: m[2].trim(), note: m[3] ?? '' }));
const shared = rows(tokenBlock(tokens, ':root {'));
const dawnT = rows(tokenBlock(tokens, ':root, [data-theme="dawn"] {'));
const duskT = Object.fromEntries(rows(tokenBlock(tokens, '[data-theme="dusk"] {')).map((r) => [r.name, r.value]));
const short = (v) => (v.length > 60 ? v.slice(0, 57) + '…' : v);
await writeFile(join(skillRef, 'tokens.md'), [
  `# dawn & dusk tokens (v${pkg.version})`, '', 'Generated from `ds/tokens.css`, `ds/base.css` and the icon sprite by `scripts/build-ds.mjs`. Use `var(--dd-NAME)`; never hard-code these values.', '',
  '## Theme colours (dawn → dusk)', '', '| token | dawn | dusk | note |', '|---|---|---|---|',
  ...dawnT.filter((r) => !/color-scheme/.test(r.name)).map((r) => `| \`--dd-${r.name}\` | \`${short(r.value)}\` | \`${short(duskT[r.name] ?? '')}\` | ${r.note} |`),
  '', '## Type, space, shape, motion (shared)', '', '| token | value |', '|---|---|',
  ...shared.filter((r) => r.name !== 'grain').map((r) => `| \`--dd-${r.name}\` | \`${short(r.value)}\` |`), '',
  '## Base classes (ds/base.css)', '',
  'Typography and layout helpers every page uses. Headings `.dd-display/.dd-h1/.dd-h2/.dd-h3` are the logo lockup (Outfit 800,',
  'lowercase, tight) for page and section titles; `.dd-h4/.dd-h5` are UI titles in sentence case.', '',
  '| class | what it does |', '|---|---|',
  ...[
    ['.dd-display .dd-h1 .dd-h2 .dd-h3', 'Lockup headings: Outfit 800, lowercase, tight tracking. Page and section titles only.'],
    ['.dd-h4 .dd-h5', 'UI titles (cards, dialogs, form sections), sentence case, 650 weight.'],
    ['.dd-lead', 'Intro paragraph under a page title: larger, muted.'],
    ['.dd-text / .dd-small / .dd-caption', 'Body paragraph / small text / caption (xs, muted).'],
    ['.dd-eyebrow', 'Small mono uppercase label above a heading.'],
    ['.dd-mono / .dd-num', 'DM Mono / tabular numerals — IDs, timestamps, figures.'],
    ['.dd-muted / .dd-faint', 'Secondary text / decoration only (faint is not for text people must read).'],
    ['.dd-stack', 'Vertical flex stack; gap from `--dd-gap` (default `--dd-space-3`).'],
    ['.dd-row', 'Wrapping horizontal row, centred; gap from `--dd-gap` (default `--dd-space-2`).'],
    ['.dd-surface', 'A tonal container: `--dd-surface` fill + box radius. No border, no shadow.'],
    ['.dd-scroll', 'Thin tonal scrollbar that appears on hover/focus.'],
    ['.dd-icon', 'Sizes an inline SVG icon to the text (1.15em).'],
    ['.dd-visually-hidden', 'Hidden on screen, read by screen readers.'],
  ].map(([c, d]) => `| ${c.split(' ').map((x) => (x.startsWith('.') ? `\`${x}\`` : x)).join(' ')} | ${d} |`), '',
  '## Tailwind CSS v4 utilities (dawn-and-dusk/tailwind.css)', '',
  'In a Tailwind app these theme keys replace Tailwind\'s palette, fonts, radii and shadows, so utilities read the tokens and',
  'follow dawn / dusk on their own. Spacing is the 5px unit: `p-4` = `--dd-space-4` = 20px. Variants: `dusk:` (alias `dark:`)',
  'and `dawn:`, following the nearest `data-theme`. Prefer token utilities to `dusk:` overrides. See `references/frameworks.md`.', '',
  '| Tailwind theme key | token | e.g. |', '|---|---|---|',
  ...tailwindTheme(tokens).filter(([k]) => !k.includes('--line-height') && !k.startsWith('--default')).map(([k, v]) => {
    const [, ns, name] = k.match(/^--([a-z]+)-?(.*)$/);
    const eg = { color: `bg-${name} text-${name} border-${name}`, font: `font-${name}`, text: `text-${name}`, leading: `leading-${name}`, tracking: `tracking-${name}`, radius: `rounded-${name}`, shadow: `shadow-${name}`, ease: `ease-${name}`, spacing: 'p-4 gap-2 w-64' }[ns] ?? '';
    return `| \`${k}\` | \`${v}\` | ${eg.split(' ').map((x) => `\`${x}\``).join(' ')} |`;
  }), '',
  '## Icons', '',
  'Solar Bold Duotone, as an SVG sprite (`assets/icons.svg`): inline the sprite once after `<body>`, then',
  '`<svg class="dd-icon" aria-hidden="true"><use href="#dd-i-NAME"/></svg>`. These are ALL the names — pick the closest; never invent one:', '',
  [...(await read('icons/icons.svg')).matchAll(/id="dd-i-([\w-]+)"/g)].map((m) => `\`${m[1]}\``).join(' '), '',
].join('\n'));

// Component catalogue: header comment + every class each component file defines.
const catalogue = [`# dawn & dusk components (v${pkg.version})`, '',
  'Generated from `ds/components/*.css`: what each component is, its classes and its `data-dd-*` hooks. Every component is plain',
  'HTML + these classes; behaviours are opt-in `data-dd-*` attributes handled by `dawn-and-dusk.js`.', '',
  '**For markup, read `components/<name>.md`** next to this file: the exact, working HTML of every docs example, the class',
  'table and the guidelines. Live demos: https://cxkw-dev.github.io/dawn-and-dusk/components/<name>', '',
  `Index: ${components.map((f) => f.replace(/\.css$/, '')).map((n) => `[${n}](#${n})`).join(' · ')}`, ''];
// A component's "own" classes are those not belonging to another component's main block (e.g. .dd-btn inside button-group).
const blockOf = (c) => c.split(/__|--/)[0];
const mains = {};
for (const f of components) {
  const counts = {};
  for (const m of (await read(`components/${f}`)).matchAll(/\.(dd-[\w-]+)/g)) counts[blockOf(m[1])] = (counts[blockOf(m[1])] || 0) + 1;
  mains[f] = Object.entries(counts).sort((a, b) => b[1] - a[1])[0]?.[0];
}
for (const f of components) {
  const src = await read(`components/${f}`);
  const name = f.replace(/\.css$/, '');
  const head = (src.match(/^\/\*([\s\S]*?)\*\//) ?? [, ''])[1].replace(/\s*\n\s*/g, ' ').trim();
  const classes = [...new Set([...src.matchAll(/\.(dd-[\w-]+)/g)].map((m) => m[1]))].filter((c) => !c.startsWith('dd-icon'));
  const foreign = new Set(Object.entries(mains).filter(([g]) => g !== f).map(([, b]) => b));
  const own = classes.filter((c) => !foreign.has(blockOf(c)) || blockOf(c) === mains[f]);
  const others = [...new Set(classes.filter((c) => !own.includes(c)).map(blockOf))];
  const attrs = [...new Set([...src.matchAll(/\[(data-dd-[\w-]+|aria-[\w-]+)/g)].map((m) => m[1]))];
  catalogue.push(`## ${name}`, '', head || '_No description._', '', `Classes: ${own.map((c) => `\`.${c}\``).join(' ')}`);
  if (others.length) catalogue.push('', `Works with: ${others.map((c) => `\`.${c}\``).join(' ')}`);
  if (attrs.length) catalogue.push('', `Attributes/states: ${attrs.map((a) => `\`${a}\``).join(' ')}`);
  catalogue.push('', `Markup: \`references/components/${name}.md\``, '');
}
const behaviorDocs = [];
for (const f of behaviors) {
  const src = await read(`behaviors/${f}`);
  const head = (src.match(/^\/\*([\s\S]*?)\*\//) ?? [, ''])[1].replace(/\s*\n\s*/g, ' ').trim();
  behaviorDocs.push(`- **${f.replace(/\.js$/, '')}** — ${head || 'see source'}`);
}
catalogue.push('## Behaviours (dawn-and-dusk.js)', '', ...behaviorDocs, '');
await writeFile(join(skillRef, 'components.md'), catalogue.join('\n'));

// The hand-written docs carry the versioned release URLs (the npm install command, starter downloads). Fill them from
// package.json so a version bump can't leave one behind, and fail if a doc has lost its install command.
const releaseLink = /https:\/\/github\.com\/cxkw-dev\/dawn-and-dusk\/releases\/download\/v[^/\s)]+\/dawn-and-dusk-(?:(html|react|next)-)?[^/\s)]+?\.(?:tgz|zip)/g;
for (const doc of ['README.md', 'library/README.md', 'skill/dawn-and-dusk/SKILL.md', 'skill/dawn-and-dusk/references/frameworks.md']) {
  const src = await readFile(join(root, doc), 'utf8');
  const filled = src.replace(releaseLink, (_, starter) => releaseAsset(pkg.version, starter));
  if (!filled.includes(`npm install ${releaseAsset(pkg.version)}`)) throw new Error(`build-ds: ${doc} has no versioned install command (npm install ${releaseAsset(pkg.version)})`);
  if (filled !== src) await writeFile(join(root, doc), filled);
}

console.log(`dawn & dusk v${pkg.version}: ${components.length} components, ${behaviors.length} behaviors → release/ + skill/`);
